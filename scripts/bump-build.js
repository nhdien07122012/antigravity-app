import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

// 1. Read or initialize version.json
const versionFile = path.join(rootDir, 'src', 'version.ts');
let buildNumber = 1;
let appVersion = '1.0.0';

if (fs.existsSync(versionFile)) {
  const content = fs.readFileSync(versionFile, 'utf8');
  const matchBuild = content.match(/BUILD_NUMBER\s*=\s*(\d+);/);
  const matchVer = content.match(/APP_VERSION\s*=\s*['"]([^'"]+)['"];/);
  if (matchBuild) {
    buildNumber = parseInt(matchBuild[1], 10) + 1;
  }
  if (matchVer) {
    appVersion = matchVer[1];
  }
}

// Ensure src directory exists
if (!fs.existsSync(path.join(rootDir, 'src'))) {
  fs.mkdirSync(path.join(rootDir, 'src'), { recursive: true });
}

// 2. Write updated src/version.ts
const versionTsContent = `// Auto-generated by scripts/bump-build.js
export const APP_VERSION = '${appVersion}';
export const BUILD_NUMBER = ${buildNumber};
export const FULL_VERSION = \`v\${APP_VERSION} (Build \${BUILD_NUMBER})\`;
export const BUILD_DATE = '${new Date().toISOString()}';
`;
fs.writeFileSync(versionFile, versionTsContent, 'utf8');
console.log(`[Version] Updated to: v${appVersion} (Build ${buildNumber})`);

// 3. Update project.pbxproj if iOS project exists
const pbxprojPath = path.join(rootDir, 'ios', 'App', 'App.xcodeproj', 'project.pbxproj');
if (fs.existsSync(pbxprojPath)) {
  let pbx = fs.readFileSync(pbxprojPath, 'utf8');
  pbx = pbx.replace(/CURRENT_PROJECT_VERSION = \d+;/g, `CURRENT_PROJECT_VERSION = ${buildNumber};`);
  pbx = pbx.replace(/MARKETING_VERSION = [^;]+;/g, `MARKETING_VERSION = ${appVersion};`);
  fs.writeFileSync(pbxprojPath, pbx, 'utf8');
  console.log(`[iOS pbxproj] CURRENT_PROJECT_VERSION synced to ${buildNumber}`);
}

export { buildNumber, appVersion };
